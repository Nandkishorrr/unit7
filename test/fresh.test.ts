// a stand-in for everything outside: branch, PR, preview, checks, merge, deploy
function fakes(app: any, orgId: string, o: { tests?: string; smoke?: boolean; watch?: string; checks?: string; moved?: boolean } = {}) {
  const calls: string[] = [];
  let main = 'a'; // the main branch's head: each merge moves it on
  Object.assign(freshDeps, {
    apply: async (_c: unknown, _a: unknown, items: unknown[], x: { branch: string; revert?: string }) => { calls.push(x.revert ? `revert ${x.revert.slice(0, 3)}` : `apply ${items.length}`); return { pushed: true, baseSha: main.repeat(40), diff: '-"next": "^14.1.0"\n+"next": "^14.2.3"', files: 'package.json | 2 +-', skipped: [] }; },
    openPr: async (_r: unknown, x: { title: string }) => { calls.push(`pr ${x.title}`); return { number: calls.length, html_url: `https://github.com/ada/shop/pull/${calls.length}` }; },
    preview: async () => { calls.push('preview'); return { ok: o.tests !== 'failed', serviceId: 'svc_preview00000', deploymentId: 'dep_preview00000', tests: { status: o.tests ?? 'passed', label: 'npm test', ...(o.tests === 'failed' && { failure: 'The test “checkout adds tax” failed (cart.test.ts).' }) } }; },
    smoke: async () => { calls.push('smoke'); return o.smoke === false ? { ok: false, rows: [], line: '/checkout answered 500 on the copy; the live app says 200.' } : { ok: true, rows: [{ path: '/', live: 200, copy: 200, liveMs: 40, copyMs: 42, ok: true }], line: 'Your 1 busiest page answered the same on the copy as on the live app.' }; },
    checks: async () => ({ open: true, merged: false, status: o.checks ?? 'success' }),
    head: async () => (o.moved ? 'z'.repeat(40) : main.repeat(40)),
    merge: async () => { calls.push('merge'); main = String.fromCharCode(main.charCodeAt(0) + 1); },
    release: async (_c: unknown, svc: { id: string }, commit?: string) => {
      calls.push(`deploy ${commit?.slice(0, 3)}`);
      const d = id('dep');
      const n = get<{ n: number }>(app.db, 'SELECT max(number) + 1 n FROM deployments WHERE service_id = ?', svc.id)!.n;
      run(app.db, `INSERT INTO deployments (id, org_id, service_id, number, status, plan, downtime_seconds) VALUES (?, ?, ?, ?, 'live', ?, 0)`, d, orgId, svc.id, n, JSON.stringify({ watch: { status: o.watch ?? 'ok', ...(o.watch === 'rolled_back' && { reason: 'errors jumped to 8% (usually 0.1%) after the deploy' }) } }));
      return { deploymentId: d, number: n, status: 'live' };
    },
    sleep: async () => undefined, pollMs: 0,
  });
  return calls;
}
const real = { ...freshDeps };

