test('OSV records become plain advisories: severity, the fix, the link; one problem under two names counts once', () => {
  const a = fromOsv(LODASH_VULN, { eco: 'npm', name: 'lodash', version: '4.17.20' });
  assert.deepEqual({ sev: a.severity, fixed: a.fixed, url: a.url, summary: a.summary }, { sev: 'high', fixed: '4.17.21', url: 'https://github.com/advisories/GHSA-35jh-r3h4-6jhm', summary: 'Command Injection in lodash' });
  const py = fromOsv({ id: 'PYSEC-2023-1', aliases: ['GHSA-aaaa-bbbb-cccc'], details: 'Django lets…', affected: [{ package: { name: 'Django', ecosystem: 'PyPI' }, ranges: [{ events: [{ introduced: '4.2' }, { fixed: '4.2.8' }] }] }] }, { eco: 'PyPI', name: 'django', version: '4.2.7' });
  assert.equal(py.fixed, '4.2.8', 'PyPI names compare normalised');
  assert.equal(py.severity, 'moderate', 'no severity said: moderate');
  const gh = fromOsv({ id: 'GHSA-aaaa-bbbb-cccc', aliases: ['PYSEC-2023-1'], summary: 'Denial of service in Django', database_specific: { severity: 'CRITICAL' }, affected: [] }, { eco: 'PyPI', name: 'django', version: '4.2.7' });
  const merged = mergeAdvisories([py, gh]);
  assert.equal(merged.length, 1);
  assert.equal(merged[0]!.id, 'GHSA-aaaa-bbbb-cccc');
  assert.equal(merged[0]!.severity, 'critical', 'the worse reading wins');
  assert.equal(merged[0]!.fixed, '4.2.8');
});

function fakeWorld(o: { vuln?: object; status?: () => string } = {}) {
  const posted: string[] = [];
  const server = createServer(async (req: IncomingMessage, res: ServerResponse) => {
    const chunks: Buffer[] = []; for await (const c of req) chunks.push(c as Buffer);
    const body = Buffer.concat(chunks).toString();
    const send = (x: unknown, code = 200) => { res.writeHead(code, { 'content-type': 'application/json' }); res.end(typeof x === 'string' ? x : JSON.stringify(x)); };
    const url = req.url!;
    if (url === '/user') return send({ login: 'ada' });
    // GitHub raw files
    const raw = /^\/repos\/ada\/shop\/contents\/([^?]+)\?ref=main$/.exec(url);
    if (raw) return raw[1] === 'package.json' ? send(PKG) : raw[1] === 'package-lock.json' ? send(NPM_LOCK) : raw[1] === 'Dockerfile' ? send('FROM node:22-alpine AS build\nFROM build\n') : send('{}', 404);
    if (url === '/repos/vercel/next.js/releases?per_page=40') return send([{ tag_name: 'v15.0.0', body: '## Breaking changes\n- Requires React 19 and Node 18.18\n- `fetch` requests are no longer cached by default ([#123](x))\n- Removed the old `next export` command\n- docs: typo' }]);
    // npm registry
    const versions: Record<string, string[]> = { '/next': ['14.1.0', '14.2.3', '15.0.0', '15.1.0-canary.1'], '/react': ['18.2.0', '18.3.1'], '/lodash': ['4.17.20', '4.17.21'], '/typescript': ['5.3.3'] };
    if (versions[url]) return send({ versions: Object.fromEntries(versions[url].map((v) => [v, {}])) });
    if (url === '/next/15.0.0') return send({ repository: { url: 'git+https://github.com/vercel/next.js.git' } });
    if (url === '/-/npm/v1/security/advisories/bulk') { posted.push(body); return send({}); }
    // OSV
    if (url === '/v1/querybatch') {
      const q = JSON.parse(body) as { queries: { package: { name: string }; version: string }[] };
      return send({ results: q.queries.map((x) => (x.package.name === 'lodash' && x.version === '4.17.20' ? { vulns: [{ id: LODASH_VULN.id }] } : {})) });
    }
    if (url === `/v1/vulns/${LODASH_VULN.id}`) return send(o.vuln ?? LODASH_VULN);
    // Docker Hub
    if (url === '/v2/namespaces/library/repositories/node/tags/22-alpine') return send({ last_updated: '2099-01-01T00:00:00Z' });
    send({}, 404);
  });
  return new Promise<{ close: () => void; posted: string[] }>((resolve) => server.listen(0, '127.0.0.1', () => {
    const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
    Object.assign(process.env, { UNIT7_GITHUB_API: base, UNIT7_NPM_REGISTRY: base, UNIT7_OSV_URL: base, UNIT7_DOCKERHUB_API: base, UNIT7_PYPI_URL: base });
    resolve({ posted, close: () => { server.close(); for (const k of ['UNIT7_GITHUB_API', 'UNIT7_NPM_REGISTRY', 'UNIT7_OSV_URL', 'UNIT7_DOCKERHUB_API', 'UNIT7_PYPI_URL']) delete process.env[k]; } });
  }));
}

