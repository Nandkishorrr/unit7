const sec = (id: string, severity: 'critical' | 'high' | 'moderate', fixed?: string) => ({ id, aliases: [], eco: 'npm' as const, pkg: '', version: '', severity, summary: 'Prototype pollution', url: `https://osv.dev/vulnerability/${id}`, source: 'osv' as const, ...(fixed && { fixed }) });
const SCAN: Pick<Scan, 'updates' | 'base'> = {
  base: [],
  updates: [
    { eco: 'npm', name: 'zod', from: '3.22.0', to: '3.22.4', bump: 'patch', direct: true, manager: 'npm' },
    { eco: 'npm', name: 'next', from: '14.1.0', to: '14.2.3', bump: 'minor', direct: true, manager: 'npm' },
    { eco: 'npm', name: 'next', from: '14.1.0', to: '15.0.0', bump: 'major', direct: true, manager: 'npm' },
    { eco: 'npm', name: 'axios', from: '1.6.0', to: '1.6.8', bump: 'patch', direct: true, manager: 'npm', security: [sec('GHSA-1', 'moderate', '1.6.8')] },
    { eco: 'npm', name: 'tar', from: '6.1.0', to: '6.2.1', bump: 'minor', direct: false, manager: 'npm', security: [sec('GHSA-2', 'critical', '6.2.1')] },
    { eco: 'npm', name: 'express', from: '4.18.0', to: '5.0.0', bump: 'major', direct: true, manager: 'npm', security: [sec('GHSA-3', 'high', '5.0.0')] },
  ],
};
const holds = (h: Partial<Hold>[]): Hold[] => h.map((x, n) => ({ id: `frh_${n}`, serviceId: null, package: null, starts: null, until: null, reason: null, ...x }));

test('the planner: security first (worst first), majors on their own, the mode decides what is in', () => {
  const p = planBatches(SCAN, { mode: 'minor', holds: [], serviceId: 'svc_x', app: 'shop' });
  assert.deepEqual(p.batches.map((b) => b.key), ['weekly', 'major:express'], 'a major with a security fix still gets its own batch');
  assert.deepEqual(p.batches[0]!.items.map((i) => i.name), ['tar', 'axios', 'next', 'zod']);
  assert.equal(p.batches[0]!.worst, 'critical');
  assert.equal(p.batches[0]!.title, '4 updates · 2 security');
  assert.deepEqual(p.later.map((i) => `${i.name}@${i.to}`), ['next@15.0.0']);
  assert.deepEqual(planBatches(SCAN, { mode: 'security', holds: [], app: 'shop' }).batches[0]!.items.map((i) => i.name), ['tar', 'axios']);
  assert.deepEqual(planBatches(SCAN, { mode: 'all', holds: [], app: 'shop' }).batches.map((b) => b.title), ['4 updates · 2 security', 'Express 4 → 5', 'Next.js 14 → 15']);
  const off = planBatches(SCAN, { mode: 'off', holds: [], app: 'shop' });
  assert.deepEqual(off.batches[0]!.items.map((i) => i.name), ['tar', 'axios'], 'off still lists security fixes (nothing runs by itself: acceptance says so)');
  // only the base image moved: a rebuild
  const img = planBatches({ updates: [], base: [{ image: 'node:22-alpine', newer: true, checked: true }] }, { mode: 'minor', holds: [], app: 'shop' });
  assert.equal(img.batches[0]!.kind, 'image');
  assert.match(img.batches[0]!.summary[0]!, /node:22-alpine got a newer build/);
});

