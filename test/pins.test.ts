  assert.equal(applyPin(repo, 'pnpm@10', 'unit7').pm!.version, '12.0.1', 'what the repo says now wins over a remembered pin');
  assert.equal(applyPin(repo, 'pnpm@10', 'you').pm!.version, '10');
  assert.equal(applyPin(pins, 'yarn@4', 'you').pm!.tool, 'pnpm', 'never another tool');
  const d = { ...detect(facts({ 'package.json': pkg({ dependencies: { express: '4' } }) }, lock9, ['package.json', 'pnpm-lock.yaml'])) };
